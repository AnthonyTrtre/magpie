import AppKit
import CryptoKit

/// Ce qu'on a lu dans le presse-papiers. L'image n'est pas encore écrite sur disque.
enum Lecture: Equatable {
    case contenu(Contenu)
    case image(png: Data, largeur: Int, hauteur: Int, empreinte: String)
}

enum Lecteur {
    /// Types posés par les gestionnaires de mots de passe et les apps qui ne veulent pas être historisées
    /// (convention nspasteboard.org). Ces copies ne sont jamais lues ni stockées.
    static let typesIgnores: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword",
    ]
    static let tailleMaxTexte = 1_000_000
    static let tailleMaxImage = 25_000_000

    /// `nil` si le presse-papiers est vide, ignoré ou trop gros.
    static func lire(_ pb: NSPasteboard) -> Lecture? {
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: typesIgnores) else { return nil }

        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            return .contenu(.fichiers(urls))
        }
        if let texte = pb.string(forType: .string) {
            let net = texte.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !net.isEmpty, texte.utf8.count <= tailleMaxTexte else { return nil }
            if let url = lien(net) { return .contenu(.lien(url)) }
            return .contenu(.texte(texte))
        }
        if let donnees = pb.data(forType: .png) ?? pb.data(forType: .tiff), donnees.count <= tailleMaxImage,
           let rep = NSBitmapImageRep(data: donnees),
           let png = rep.representation(using: .png, properties: [:]) {
            let empreinte = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            return .image(png: png, largeur: rep.pixelsWide, hauteur: rep.pixelsHigh, empreinte: empreinte)
        }
        return nil
    }

    /// Un texte qui n'est qu'une adresse web devient un lien.
    static func lien(_ texte: String) -> URL? {
        guard !texte.contains(where: \.isWhitespace), let url = URL(string: texte),
              let schema = url.scheme?.lowercased(), ["http", "https"].contains(schema), url.host != nil else { return nil }
        return url
    }
}
